import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node fonts.extract.mjs <lvgl>/src/font');

function block(source, start) {
  const at = source.indexOf(start);
  if (at < 0) throw new Error(`missing ${start}`);
  return source.slice(source.indexOf('{', at) + 1, source.indexOf('};', at));
}

const numbers = (text) => text.replace(/\/\*[\s\S]*?\*\//g, '').match(/-?(?:0x[0-9a-f]+|\d+)/gi).map(Number);
const field = (source, name) => Number(new RegExp(`\\.${name}\\s*=\\s*(-?\\d+)`).exec(source)[1]);

function font(size) {
  const source = readFileSync(join(dir, `lv_font_montserrat_${size}.c`), 'utf8');
  const advances = [...block(source, 'glyph_dsc[] =').matchAll(/\.adv_w = (\d+)/g)].map((m) => Number(m[1]));
  const sparse = numbers(block(source, 'unicode_list_1[] ='));
  const cmaps = block(source, 'cmaps[] =');
  const ranges = [...cmaps.matchAll(/\.range_start = (\d+), \.range_length = (\d+), \.glyph_id_start = (\d+)/g)].map((m) => m.slice(1).map(Number));
  const [[asciiStart, asciiLength, asciiFirst], [sparseStart, , sparseFirst]] = ranges;
  const codepoints = [];
  for (let i = 0; i < asciiLength; i++) codepoints[asciiFirst + i] = asciiStart + i;
  sparse.forEach((offset, i) => (codepoints[sparseFirst + i] = sparseStart + offset));
  const left = numbers(block(source, 'kern_left_class_mapping[] ='));
  const right = numbers(block(source, 'kern_right_class_mapping[] ='));
  const values = numbers(block(source, 'kern_class_values[] ='));
  const glyphs = [];
  for (let gid = 1; gid < codepoints.length; gid++) glyphs.push([codepoints[gid], advances[gid], left[gid], right[gid]]);
  return {
    size,
    lineHeight: field(source, 'line_height'),
    baseLine: field(source, 'base_line'),
    kernScale: field(source, 'kern_scale'),
    rightClasses: field(source, 'right_class_cnt'),
    glyphs,
    kerning: Buffer.from(Int8Array.from(values).buffer).toString('base64'),
  };
}

const fonts = [48, 28, 14].map(font);
const lines = [
  '// Generated by fonts.extract.mjs from LVGL 9 lv_font_montserrat_48.c, _28.c, and _14.c. Do not edit.',
  '// Each glyph is [codepoint, advance in 1/16 px, left kerning class, right kerning class].',
  '// kerning holds the int8 class pair values, row by left class, in base64.',
  '',
  "import type { FontData } from './text.ts';",
  '',
  ...fonts.map(
    (f) =>
      `export const MONTSERRAT_${f.size}: FontData = ${JSON.stringify({ ...f, glyphs: undefined, kerning: undefined }).replace(/,?"(glyphs|kerning)":null/g, '').slice(0, -1)}, glyphs: ${JSON.stringify(f.glyphs)}, kerning: '${f.kerning}' };`,
  ),
  '',
];
writeFileSync(join(import.meta.dirname, 'fonts.data.ts'), lines.join('\n'));
console.log(fonts.map((f) => `${f.size}: ${f.glyphs.length} glyphs, line ${f.lineHeight}, base ${f.baseLine}`).join('\n'));
