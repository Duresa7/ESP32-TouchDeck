import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const lvgl = process.argv[2];
if (!lvgl) throw new Error('usage: node fonts.extract.mjs <lvgl>/src/font');
const firmware = join(import.meta.dirname, '../../../../../firmware/components/ui/fonts');

function block(source, start) {
  const at = source.indexOf(start);
  if (at < 0) throw new Error(`missing ${start}`);
  return source.slice(source.indexOf('{', at) + 1, source.indexOf('};', at));
}

const numbers = (text) => text.replace(/\/\*[\s\S]*?\*\//g, '').match(/-?(?:0x[0-9a-f]+|\d+)/gi).map(Number);
const field = (source, name) => Number(new RegExp(`\\.${name}\\s*=\\s*(-?\\d+)`).exec(source)[1]);

function codepointsOf(source) {
  const codepoints = [];
  for (const cmap of block(source, 'cmaps[] =').matchAll(/\{([^{}]*)\}/g)) {
    const [, start, length, first] = /\.range_start = (\d+), \.range_length = (\d+), \.glyph_id_start = (\d+)/.exec(cmap[1]).map(Number);
    const list = /\.unicode_list = (\w+)/.exec(cmap[1])[1];
    if (list === 'NULL') {
      for (let i = 0; i < length; i++) codepoints[first + i] = start + i;
    } else {
      numbers(block(source, `${list}[] =`)).forEach((offset, i) => (codepoints[first + i] = start + offset));
    }
  }
  return codepoints;
}

function font(file, name) {
  const source = readFileSync(file, 'utf8');
  const advances = [...block(source, 'glyph_dsc[] =').matchAll(/\.adv_w = (\d+)/g)].map((m) => Number(m[1]));
  const codepoints = codepointsOf(source);
  const byClass = field(source, 'kern_classes') === 1;
  const left = byClass ? numbers(block(source, 'kern_left_class_mapping[] =')) : [];
  const right = byClass ? numbers(block(source, 'kern_right_class_mapping[] =')) : [];
  const glyphs = [];
  for (let gid = 1; gid < codepoints.length; gid++) glyphs.push([codepoints[gid], advances[gid], left[gid] ?? 0, right[gid] ?? 0]);
  const values = numbers(block(source, byClass ? 'kern_class_values[] =' : 'kern_pair_values[] ='));
  let kerning;
  if (byClass) {
    kerning = { rightClasses: field(source, 'right_class_cnt'), kerning: Buffer.from(Int8Array.from(values).buffer).toString('base64') };
  } else {
    const ids = numbers(block(source, 'kern_pair_glyph_ids[] ='));
    kerning = { rightClasses: 0, kerning: '', pairs: values.map((value, i) => [codepoints[ids[2 * i]], codepoints[ids[2 * i + 1]], value]) };
  }
  return {
    name,
    data: { size: Number(/Size: (\d+) px/.exec(source)[1]), lineHeight: field(source, 'line_height'), baseLine: field(source, 'base_line'), kernScale: field(source, 'kern_scale'), ...kerning, glyphs },
  };
}

const fonts = [
  font(join(firmware, 'ui_font_medium_44.c'), 'ARCHIVO_MEDIUM_44'),
  font(join(firmware, 'ui_font_medium_26.c'), 'ARCHIVO_MEDIUM_26'),
  font(join(firmware, 'ui_font_medium_22.c'), 'ARCHIVO_MEDIUM_22'),
  font(join(firmware, 'ui_font_semibold_32.c'), 'ARCHIVO_SEMIBOLD_32'),
  font(join(firmware, 'ui_font_semibold_40.c'), 'ARCHIVO_SEMIBOLD_40'),
  font(join(firmware, 'ui_font_nameplate_26.c'), 'ARCHIVO_NAMEPLATE_26'),
  font(join(lvgl, 'lv_font_montserrat_48.c'), 'MONTSERRAT_48'),
];

const line = ({ name, data: { glyphs, pairs, ...rest } }) => {
  const head = JSON.stringify(rest).slice(0, -1);
  return `export const ${name}: FontData = ${head},${pairs ? ` "pairs": ${JSON.stringify(pairs)},` : ''} "glyphs": ${JSON.stringify(glyphs)} };`;
};

const lines = [
  '// Generated by fonts.extract.mjs from the Firmware fonts in firmware/components/ui/fonts and LVGL 9 lv_font_montserrat_48.c. Do not edit.',
  '// Each glyph is [codepoint, advance in 1/16 px, left kerning class, right kerning class].',
  '// kerning holds the int8 class pair values, row by left class, in base64. A font kerned by pairs lists',
  '// [left codepoint, right codepoint, value] in pairs instead.',
  '',
  "import type { FontData } from './text.ts';",
  '',
  ...fonts.map(line),
  '',
];
writeFileSync(join(import.meta.dirname, 'fonts.data.ts'), lines.join('\n'));
console.log(fonts.map(({ name, data }) => `${name}: ${data.glyphs.length} glyphs, line ${data.lineHeight}, base ${data.baseLine}${data.pairs ? `, ${data.pairs.length} pairs` : ''}`).join('\n'));
